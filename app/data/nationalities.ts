export type NationalityOption = {
  id: string;
  name: string;
  code: number | string;
  iso: string;
  flagUrl: string;
};

export function getNationalitiesForGame(gameName: string): NationalityOption[] {
  return Object.entries(ACC_NATIONALITIES)
    .map(([rawName, code]) => {
      const iso = COUNTRY_ISO_MAP[rawName] || "un";
      const flagUrl = iso === "un" ? "https://flagcdn.com/w40/un.png" : `https://flagcdn.com/w40/${iso}.png`;
      const name = rawName.replace(/([a-z])([A-Z])/g, "$1 $2").trim();
      return {
        id: gameName === "ACC" ? String(code) : rawName,
        name,
        code: gameName === "ACC" ? code : rawName,
        iso,
        flagUrl,
      };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}
